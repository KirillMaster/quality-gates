using System.Globalization;
using System.Text;

namespace KirillMaster.QualityGates.Cli.Domain.Grandfather;

public static class GrandfatherSuppressions
{
    public static string Render(IEnumerable<string> memberDocIds, DateOnly date)
    {
        var ordered = new List<string>(memberDocIds);
        ordered.Sort(StringComparer.Ordinal);
        var stamp = date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);

        var text = new StringBuilder();
        text.Append("// <auto-generated>quality-gates grandfather: do not edit; shrink by fixing call sites.</auto-generated>\n");
        text.Append("using System.Diagnostics.CodeAnalysis;\n\n");

        string? previous = null;
        foreach (var id in ordered)
        {
            if (id == previous)
            {
                continue;
            }

            previous = id;
            text.Append("[assembly: SuppressMessage(\"ApiDesign\", \"RS0030\", Scope = \"member\", Target = \"~")
                .Append(id)
                .Append("\", Justification = \"grandfathered ")
                .Append(stamp)
                .Append(": pre-existing banned API call\")]\n");
        }

        return text.ToString();
    }
}
